import { zipSync, strToU8 } from 'fflate';
import type { Character } from '../core/character';
import { triangleCount } from '../core/mesh';
import { exportFBX } from './fbx';
import { exportGLB } from './glb';
import { exportOBJ } from './obj';

export type ExportFormat = 'glb' | 'fbx' | 'obj' | 'zip';

export interface ExportFile {
  name: string;
  data: Uint8Array;
  mime: string;
}

/** Safe file stem from the character name. */
export function fileStem(name: string): string {
  return name.trim().replace(/[^a-zA-Z0-9_-]+/g, '_').replace(/^_+|_+$/g, '') || 'character';
}

export function exportCharacter(ch: Character, format: ExportFormat, extras: { previewPng?: Uint8Array } = {}): ExportFile[] {
  const stem = fileStem(ch.params.name);
  const objName = stem;
  switch (format) {
    case 'glb':
      return [{ name: `${stem}.glb`, data: exportGLB(ch.mesh, objName), mime: 'model/gltf-binary' }];
    case 'fbx':
      return [{ name: `${stem}.fbx`, data: exportFBX(ch.mesh, objName), mime: 'application/octet-stream' }];
    case 'obj': {
      const { obj, mtl } = exportOBJ(ch.mesh, objName, `${stem}.mtl`);
      return [
        { name: `${stem}.obj`, data: strToU8(obj), mime: 'text/plain' },
        { name: `${stem}.mtl`, data: strToU8(mtl), mime: 'text/plain' },
      ];
    }
    case 'zip': {
      const files: Record<string, Uint8Array> = {};
      for (const f of ['glb', 'fbx', 'obj'] as const)
        for (const file of exportCharacter(ch, f)) files[`${stem}/${file.name}`] = file.data;
      files[`${stem}/${stem}.params.json`] = strToU8(JSON.stringify(ch.params, null, 2));
      if (extras.previewPng) files[`${stem}/preview.png`] = extras.previewPng;
      files[`${stem}/README.txt`] = strToU8(readme(ch, stem));
      return [{ name: `${stem}.zip`, data: zipSync(files, { level: 6 }), mime: 'application/zip' }];
    }
  }
}

function readme(ch: Character, stem: string): string {
  const { proportions: pr, mesh } = ch;
  return [
    `${ch.params.name} - generated by 3d-gen`,
    '',
    `Height:     ${pr.H.toFixed(2)} m`,
    `Triangles:  ${triangleCount(mesh)}`,
    `Vertices:   ${mesh.positions.length / 3}`,
    `Materials:  ${mesh.materials.map((m) => m.name).join(', ')}`,
    `Pose:       ${ch.params.pose}-pose`,
    '',
    'Files',
    `  ${stem}.glb          glTF 2.0 binary (metres, +Y up, faces +Z)`,
    `  ${stem}.fbx          FBX 7.4 binary (centimetres, +Y up, faces +Z)`,
    `  ${stem}.obj / .mtl   Wavefront OBJ (metres)`,
    `  ${stem}.params.json  Generator settings - load to regenerate this character`,
    '',
  ].join('\n');
}
