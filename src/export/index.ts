import { strToU8, zipSync, type Zippable } from 'fflate';
import type { AssetLibrary } from '../core/assets';
import { textureFiles, type Character } from '../core/human';
import { triangleCount } from '../core/mesh';
import { exportFBX } from './fbx';
import { exportGLB, mimeOf } from './glb';
import { exportOBJ } from './obj';

export type ExportFormat = 'glb' | 'fbx' | 'obj' | 'zip';

export interface ExportFile {
  name: string;
  data: Uint8Array;
  mime: string;
}

/** Safe file stem from the character name. */
export function fileStem(name: string): string {
  return name.trim().replace(/[^a-zA-Z0-9_-]+/g, '_').replace(/^_+|_+$/g, '') || 'character';
}

async function loadTextures(lib: AssetLibrary, ch: Character): Promise<Map<string, Uint8Array>> {
  const files = textureFiles(ch.mesh);
  const data = await Promise.all(files.map((f) => lib.texture(f)));
  return new Map(files.map((f, i) => [f, data[i]]));
}

const LICENSE = `Character assets derive from MakeHuman (makehumancommunity.org), released as
CC0 1.0 (public domain) by Data Collection AB, Joel Palmius and Jonas Hauquier.
Free for commercial and non-commercial use, no attribution required.
`;

export async function exportCharacter(
  lib: AssetLibrary, ch: Character, format: ExportFormat, extras: { previewPng?: Uint8Array } = {},
): Promise<ExportFile> {
  const stem = fileStem(ch.params.name);
  const textures = await loadTextures(lib, ch);
  const objFiles = (): Zippable => {
    const { obj, mtl } = exportOBJ(ch.mesh, stem, `${stem}.mtl`);
    const files: Zippable = { [`${stem}.obj`]: strToU8(obj), [`${stem}.mtl`]: strToU8(mtl) };
    for (const [f, d] of textures) files[`textures/${f}`] = [d, { level: 0 }];
    return files;
  };
  switch (format) {
    case 'glb':
      return { name: `${stem}.glb`, data: exportGLB(ch.mesh, stem, textures), mime: 'model/gltf-binary' };
    case 'fbx':
      return { name: `${stem}.fbx`, data: exportFBX(ch.mesh, stem, textures), mime: 'application/octet-stream' };
    case 'obj':
      return { name: `${stem}_obj.zip`, data: zipSync(objFiles(), { level: 6 }), mime: 'application/zip' };
    case 'zip': {
      const files: Zippable = {
        [`${stem}.glb`]: [exportGLB(ch.mesh, stem, textures), { level: 0 }],
        [`${stem}.fbx`]: exportFBX(ch.mesh, stem, textures),
        obj: objFiles(),
        [`${stem}.params.json`]: strToU8(JSON.stringify(ch.params, null, 2)),
        'README.txt': strToU8(readme(ch, stem)),
        'LICENSE.txt': strToU8(LICENSE),
      };
      if (extras.previewPng) files['preview.png'] = [extras.previewPng, { level: 0 }];
      return { name: `${stem}.zip`, data: zipSync({ [stem]: files }, { level: 6 }), mime: 'application/zip' };
    }
  }
}

function readme(ch: Character, stem: string): string {
  const { mesh } = ch;
  const quads = mesh.groups.reduce((n, g) => n + g.polySizes.length, 0);
  return [
    `${ch.params.name} - generated by 3d-gen`,
    '',
    `Height:     ${(ch.height * 100).toFixed(0)} cm`,
    `Polygons:   ${quads} (${triangleCount(mesh)} triangles)`,
    `Vertices:   ${mesh.positions.length / 3}`,
    `Materials:  ${mesh.materials.map((m) => m.name).join(', ')}`,
    `Detail:     ${ch.params.detail}`,
    '',
    'Files',
    `  ${stem}.glb          glTF 2.0 binary, textures embedded (metres, +Y up, faces +Z)`,
    `  ${stem}.fbx          FBX 7.4 binary, textures embedded (centimetres, +Y up, faces +Z)`,
    `  obj/                 Wavefront OBJ + MTL + textures/ (metres, quads)`,
    `  ${stem}.params.json  Generator settings - load to regenerate this character`,
    '',
    `Textures: ${[...new Set(mesh.materials.flatMap((m) => [m.map, m.normalMap]).filter(Boolean))].map((f) => `${f} (${mimeOf(f!)})`).join(', ')}`,
    '',
  ].join('\n');
}
