/**
 * Bakes the motion-capture clips: reads the CMU takes (BVH, downloaded by `npm run setup-assets`
 * into vendor/mocap/cmu), retargets and trims them (src/core/anim/mocap.ts), and writes compact
 * data to src/core/anim/clips/mocap-data.ts, which is committed so builds and tests don't need
 * the source files.
 *   npm run build-mocap
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { bakeMocap, mirrorBvh, mocapClip, parseBvh, type MocapData } from '../src/core/anim/mocap';
import { MOCAP_TAKES } from './mocap-takes';

const ROOT = join(import.meta.dirname, '..');
const out: Record<string, MocapData> = {};
for (const t of MOCAP_TAKES) {
  const src = parseBvh(readFileSync(join(ROOT, 'vendor/mocap/cmu', `${t.take}.bvh`), 'utf8'));
  const bvh = t.mirror ? mirrorBvh(src) : src;
  const clip = mocapClip(bvh, { ...t.cut, id: t.id, name: t.id, category: 'Locomotion', loop: t.loop, take: t.take });
  out[t.id] = bakeMocap(clip, 60, t.hands, t.ground);
  console.log(`[build-mocap] ${t.id.padEnd(14)} ${t.take}  ${clip.duration.toFixed(2)} s  ${(out[t.id].rot.length / 1024).toFixed(0)} KB`);
}
const src = `/**
 * Motion-capture clip data, generated by scripts/build-mocap.ts from the CMU Graphics Lab Motion
 * Capture Database (mocap.cs.cmu.edu; created with funding from NSF EIA-0196217). Do not edit.
 */
import type { MocapData } from '../mocap';

export const MOCAP_DATA: Record<string, MocapData> = ${JSON.stringify(out)};
`;
writeFileSync(join(ROOT, 'src/core/anim/clips/mocap-data.ts'), src);
console.log(`[build-mocap] wrote ${Object.keys(out).length} clips, ${(src.length / 1024).toFixed(0)} KB`);
